#!/usr/bin/env python3
"""Build the "HIM Casebook: Uncommon Conditions" book (him-uncommon-conditions-data.js).

Each case is one lesson, stored as cases/NN-<slug>.json. Card format matches
tools/icd10cm-guidelines specs: intro/concept/example/application cards with a
diagram spec ({title, sub, cols, boxes:[{h,b}]}), and quiz cards with
{question, options[], correct, explanation, visual:{topic, hint}}.

    python3 tools/him-uncommon-conditions/build.py [--codes icd10cm_order_YYYY.txt]

With --codes (the CMS icd10cm_order_YYYY.txt file from "code descriptions in tabular order", which also lists category headers), every ICD-10-CM
code or category cited in a case must exist in that code set, or the build fails.
"""
import glob, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, 'tools', 'icd10cm-guidelines'))
from build import grid, Overflow  # same diagram renderer and size checks as the guidelines book

def load_codes(path):
    codes = set()
    for line in open(path, encoding='utf-8', errors='ignore'):
        parts = line.split()
        c = (parts[1] if parts and parts[0].isdigit() and len(parts) > 1 else (parts[0] if parts else ''))
        if c:
            codes.add(c)
            codes.add(c[:3] + ('.' + c[3:] if len(c) > 3 else ''))
    return codes

def main():
    codes = None
    if '--codes' in sys.argv:
        codes = load_codes(sys.argv[sys.argv.index('--codes') + 1])
    lessons, errs = [], []
    for f in sorted(glob.glob(os.path.join(HERE, 'cases', '*.json'))):
        case = json.load(open(f, encoding='utf-8'))
        cards = []
        for i, c in enumerate(case['cards']):
            where = f"{os.path.basename(f)} card {i+1}"
            text = json.dumps(c)
            if codes is not None:
                for t in set(re.findall(r'\b[A-Z]\d[0-9A-Z](?:\.[0-9A-Z]{1,4})?(?=[^0-9A-Za-z]|$)', text)):
                    if t.rstrip('-') not in codes:
                        errs.append(f'{where}: {t} is not in the code set')
            try:
                if c['type'] == 'quiz':
                    v = c['visual']
                    svg = grid('KNOWLEDGE CHECK', case['short'], [{'h': v['topic'], 'b': v['hint']}], 1)
                    if not (3 <= len(c['options']) <= 4 and 0 <= c['correct'] < len(c['options'])):
                        errs.append(f'{where}: bad options/correct')
                    cards.append({'type': 'quiz', 'question': c['question'],
                                  'options': [{'text': o, 'correct': j == c['correct']} for j, o in enumerate(c['options'])],
                                  'explanation': c['explanation'],
                                  'visual': {'type': 'diagram', 'svg': svg, 'caption': 'Knowledge check: ' + v['topic']}})
                else:
                    v = c['visual']
                    svg = grid(v['title'], v.get('sub', ''), v['boxes'], v.get('cols', 2))
                    cards.append({'type': c['type'], 'title': c['title'], 'content': c['content'],
                                  'visual': {'type': 'diagram', 'svg': svg, 'caption': v.get('caption') or c['title']}})
            except Overflow as e:
                errs.append(f'{where}: {e}')
        if sum(1 for c in cards if c['type'] == 'quiz') < 2:
            errs.append(f'{f}: needs at least 2 quizzes')
        lessons.append({'id': case['id'], 'title': case['title'], 'duration': case['duration'], 'completed': False, 'cards': cards})
    if errs:
        print('\n'.join('ERROR: ' + e for e in errs)); sys.exit(1)
    book = {'id': 'him-uncommon-conditions', 'title': 'HIM Casebook: Uncommon Conditions',
            'author': 'SYNTHESIS Learning',
            'description': 'Real questions from the billing desk about conditions and visit types that do not come up every day: '
                           'what the visit is, who can treat it, and which ICD-10-CM codes fit, checked against the official code set and the '
                           'Official Guidelines. One case per lesson; new cases are added as they come up.',
            'lessons': len(lessons), 'duration': sum(l['duration'] for l in lessons), 'progress': 0, 'category': 'him',
            'cards': sum(len(l['cards']) for l in lessons), 'lessonList': lessons}
    out = os.path.join(REPO, 'him-uncommon-conditions-data.js')
    open(out, 'w', encoding='utf-8').write(
        '// External book module: HIM Casebook: Uncommon Conditions.\n'
        '// GENERATED by tools/him-uncommon-conditions/build.py from cases/*.json; do not edit by hand.\n'
        '// Loaded BEFORE data.js; integrated into the HIM category via externalBooks.\n'
        'window.HIM_UNCOMMON_CONDITIONS_BOOK = ' + json.dumps(book, ensure_ascii=False, indent=1) + ';\n')
    print('wrote', out, len(lessons), 'case(s)', book['cards'], 'cards')

if __name__ == '__main__':
    main()
